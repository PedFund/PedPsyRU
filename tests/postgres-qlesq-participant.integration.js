"use strict";
const {test}=require("node:test"),assert=require("node:assert/strict");
test("Q-LES-Q 36: participant form, saved draft, resume and server scoring",async t=>{
 const x=await require("./qlesq-fixture.js").qlesqFixture();t.after(()=>x.close());
 const {workspaceFixture,headers}=require("./workspace-fixture.js"),{csrfFor}=require("../storage/access.js");
 const w=workspaceFixture(x.f,undefined,{workbench:true,admissions:true,passports:true,consents:true});t.after(()=>w.app.close());
 const h={...headers,cookie:"pedpsy_v2_demo="+x.session.token,"x-pedpsy-csrf":csrfFor(x.session.token)};
 const endpoint="/api/v2/participant/attempts/"+x.qlesq;
 let res=await w.app.inject({url:endpoint+"/form",headers:h});
 assert.equal(res.statusCode,200,JSON.stringify(res.json()));const form=res.json();
 assert.equal(form.items.length,36);assert.equal(form.items[27].options[0].text,"1 – Очень часто");
 assert.equal(form.items[27].options[9].text,"10 – Никогда");
 const answers=form.items.map(i=>({item_id:i.id,value:"5"}));
 const save=(revision,rows)=>w.app.inject({method:"PUT",url:endpoint+"/draft",headers:h,payload:{expected_revision:revision,current_item_id:"q01",responses:rows}});
 res=await save(0,answers.slice(0,10));assert.equal(res.statusCode,200,JSON.stringify(res.json()));
 assert.deepEqual((await w.app.inject({url:endpoint,headers:h})).json().responses,answers.slice(0,10));
 assert.equal((await w.app.inject({method:"POST",url:endpoint+"/complete",headers:h,payload:{expected_revision:1}})).statusCode,422);
 assert.equal((await save(1,answers)).statusCode,200);
 res=await w.app.inject({method:"POST",url:endpoint+"/complete",headers:h,payload:{expected_revision:2}});
 assert.equal(res.statusCode,200,JSON.stringify(res.json()));const result=res.json();
 assert.equal(result.measures.find(m=>m.code==="optimism").value,22);
 assert.equal(result.measures.find(m=>m.code==="quality_of_life_total").value,184);
 assert.equal(result.measures.find(m=>m.code==="quality_of_life_index").value,184/9);
 assert.equal(result.classifications.find(c=>c.code==="quality_of_life_level").value,"Низкий");
 assert.equal(JSON.stringify(result).includes("key_digest"),false);
 assert.deepEqual((await w.app.inject({url:endpoint+"/result",headers:h})).json(),result);
 assert.deepEqual((await w.app.inject({method:"POST",url:endpoint+"/complete",headers:h,payload:{expected_revision:2}})).json(),result);
 assert.equal((await save(3,answers)).statusCode,409);
 const outsider={...h,cookie:"pedpsy_v2_demo="+x.f.raw};
 assert.equal((await w.app.inject({url:endpoint+"/form",headers:outsider})).statusCode,404);
});
