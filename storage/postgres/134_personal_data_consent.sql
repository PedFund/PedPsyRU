В зависимости от содержания исследования и используемых функций платформы могут обрабатываться: регистрационные и контактные данные; социально-демографические сведения; ответы на вопросы анкет, тестов и диагностических методик; результаты выполнения исследовательских заданий; технические данные, связанные с использованием платформы.

4. Порядок обработки персональных данных

Обработка персональных данных может включать сбор, запись, систематизацию, накопление, хранение, уточнение, извлечение, использование, предоставление доступа уполномоченным лицам, обезличивание, блокирование, удаление и уничтожение данных.

