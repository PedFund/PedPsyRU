#!/usr/bin/env node
// Generates the append-only migration that lets approved results be stored. The live
// constraint body is read from the local synthetic stand, its existing pinned triples
// are re-emitted verbatim, and the approved releases are appended. Run only against
// the local demo stand described in LOCAL_DEMO.md.
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const {Pool} = require("pg");
const {validateConfig} = require("./local-demo.js");
const {approvedV1Releases} = require("../storage/approved-v1-release.js");

const root = path.resolve(__dirname, "..");
const output = path.join(root, "storage", "postgres", "052_approved_v1_results.sql");

async function main() {
  const owner = validateConfig(JSON.parse(fs.readFileSync(path.join(root, ".local/demo-stand/owner.json"), "utf8")), "owner");
  const pool = new Pool({...owner, max: 1, ssl: false});
  try {
    const {rows} = await pool.query("SELECT pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conname='result_pinned_payload'");
    if (!rows.length) throw new Error("RESULT_CONSTRAINT_NOT_FOUND");
    const definition = rows[0].def;
    const triples = [...definition.matchAll(/method_version_id'::text\) = '([^']+)'::text\) AND \(handler_version = '([^']+)'::text\) AND \(key_digest = '([^']+)'::text\)/g)]
      .map(match => ({method_version_id: match[1], handler_version: match[2], key_digest: match[3]}));
    if (!triples.length) throw new Error("NO_PINNED_TRIPLES");
    const known = new Set(triples.map(triple => triple.method_version_id + "|" + triple.handler_version));
    const added = approvedV1Releases().releases
      .filter(release => !known.has(release.methodVersionId + "|" + release.handlerVersion))
      .map(release => ({method_version_id: release.methodVersionId, handler_version: release.handlerVersion, key_digest: release.keyDigest}));
    const all = [...triples, ...added];
    const clause = triple => `(((payload ->> 'method_version_id'::text) = '${triple.method_version_id}'::text) AND (handler_version = '${triple.handler_version}'::text) AND (key_digest = '${triple.key_digest}'::text))`;
    const sql = [
      "SET LOCAL search_path=pedpsy,pg_catalog;",
      "-- 052: allow stored results for the approved-library releases.",
      "-- Generated by scripts/generate-approved-v1-results.js from the pinned constraint:",
      "-- every previously accepted identity is kept, the approved ones are appended.",
      "ALTER TABLE attempt_results DROP CONSTRAINT IF EXISTS result_pinned_payload;",
      "ALTER TABLE attempt_results ADD CONSTRAINT result_pinned_payload CHECK (COALESCE((((payload ->> 'status'::text) = 'scored'::text)",
      "  AND ((payload ->> 'contract_version'::text) = contract_version)",
      "  AND ((payload ->> 'handler_version'::text) = handler_version)",
      "  AND (((payload -> 'calculation'::text) ->> 'key_digest'::text) = key_digest)",
      "  AND (" + all.map(clause).join(" OR ") + ")), false));"
    ].join("\n");
    fs.writeFileSync(output, sql + "\n", "utf8");
    console.log("written " + path.relative(root, output) + " triples=" + all.length + " added=" + added.length);
  } finally { await pool.end(); }
}

if (require.main === module) main().catch(error => { console.error("generator stopped:", error.message); process.exitCode = 1; });
module.exports = {main};
