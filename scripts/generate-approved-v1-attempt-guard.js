#!/usr/bin/env node
// Emits the append-only migration that teaches the completion guard the approved item
// counts. The live function body is read from the local synthetic stand and re-emitted
// with additional WHEN clauses; nothing else in the guard changes.
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const {Pool} = require("pg");
const {validateConfig} = require("./local-demo.js");
const {approvedV1Releases} = require("../storage/approved-v1-release.js");

const root = path.resolve(__dirname, "..");
const output = path.join(root, "storage", "postgres", "053_approved_v1_attempt_guard.sql");

async function main() {
  const owner = validateConfig(JSON.parse(fs.readFileSync(path.join(root, ".local/demo-stand/owner.json"), "utf8")), "owner");
  const pool = new Pool({...owner, max: 1, ssl: false});
  try {
    const {rows} = await pool.query("SELECT pg_get_functiondef('pedpsy.guard_attempt'::regproc) AS def");
    if (!rows.length) throw new Error("GUARD_NOT_FOUND");
    const definition = rows[0].def;
    const known = new Set([...definition.matchAll(/'([a-z0-9_]+)' THEN (\d+)/g)].map(match => match[1] + "|" + match[2]));
    const additions = approvedV1Releases().releases
      .filter(release => !known.has(release.id + "|" + release.itemCount))
      .map(release => `WHEN (SELECT method_id FROM pedpsy.instrument_releases WHERE id=NEW.release_id)='${release.id}' THEN ${release.itemCount} `);
    if (!additions.length) { console.log("nothing to append: every item count is already pinned"); return; }
    if (!definition.includes("ELSE 30 END")) throw new Error("DEFAULT_CASE_NOT_FOUND");
    const patched = definition.replace("ELSE 30 END", additions.join("") + "ELSE 30 END");
    const sql = [
      "SET LOCAL search_path=pedpsy,pg_catalog;",
      "-- 053: teach the completion guard the approved item counts.",
      "-- Generated by scripts/generate-approved-v1-attempt-guard.js from the live",
      "-- pedpsy.guard_attempt definition; only the counts CASE is extended.",
      patched.trim()
    ].join("\n");
    fs.writeFileSync(output, sql + "\n", "utf8");
    console.log("written " + path.relative(root, output) + " additions=" + additions.length);
  } finally { await pool.end(); }
}

if (require.main === module) main().catch(error => { console.error("generator stopped:", error.message); process.exitCode = 1; });
module.exports = {main};
