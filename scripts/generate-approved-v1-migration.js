#!/usr/bin/env node
// Generates the append-only migration that pins the approved-library releases.
// The existing allowlist body is copied verbatim from the latest definition and the
// new clauses are appended, so previously pinned releases cannot drift.
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const {approvedV1Releases} = require("../storage/approved-v1-release.js");

const root = path.resolve(__dirname, "..");
const source = path.join(root, "storage", "postgres", "044_gses_release.sql");
const target = path.join(root, "storage", "postgres", "048_approved_v1_releases.sql");

const sql = fs.readFileSync(source, "utf8");
const allowStart = sql.indexOf("CREATE OR REPLACE FUNCTION constructor_release_allowed");
const allowEnd = sql.indexOf("$$;", allowStart);
if (allowStart < 0 || allowEnd < 0) throw new Error("ALLOWLIST_NOT_FOUND");
const allowBody = sql.slice(allowStart, allowEnd).trimEnd();
const guardStart = sql.indexOf("CREATE OR REPLACE FUNCTION guard_assignment");
const guardEnd = sql.indexOf("$$;", guardStart);
if (guardStart < 0 || guardEnd < 0) throw new Error("GUARD_NOT_FOUND");
const guardBody = sql.slice(guardStart, guardEnd);

const {releases, unsupported} = approvedV1Releases();
if (!releases.length) throw new Error("NO_RELEASES");

const clause = release => ` OR EXISTS(SELECT 1 FROM pedpsy.instrument_releases r WHERE r.id=release AND r.method_id='${release.id}'
   AND r.form_id='${release.form.id}' AND r.form_version='${release.form.version}' AND r.method_version_id='${release.methodVersionId}'
   AND r.handler_version='${release.handlerVersion}' AND r.contract_version='1.0' AND r.verification_state='legacy_checked'
   AND r.publication_state='draft' AND r.form_digest='${release.formDigest}' AND r.key_digest='${release.keyDigest}'
   AND (SELECT count(*) FROM pedpsy.release_items i WHERE i.release_id=r.id)=${release.itemCount}
   AND NOT EXISTS(SELECT 1 FROM pedpsy.release_items i WHERE i.release_id=r.id
     AND (i.ordinal>${release.itemCount} OR i.options IS DISTINCT FROM r.form_snapshot->'items'->(i.ordinal-1)->'options')))`;

const newAllow = allowBody + releases.map(clause).join("") + "\n";

const cases = releases.map(release => `WHEN (SELECT method_id FROM pedpsy.instrument_releases WHERE id=NEW.release_id)='${release.id}' THEN ${release.itemCount} `).join("");
const newGuard = guardBody.replace("ELSE 30 END)", cases + "ELSE 30 END)");
if (newGuard === guardBody) throw new Error("GUARD_CASE_NOT_FOUND");

const header = [
  "SET LOCAL search_path=pedpsy,pg_catalog;",
  "-- 048: pin the approved-library releases that fit the single-choice screen.",
  "-- Generated by scripts/generate-approved-v1-migration.js from",
  "--   methods/approved/v1/keys/*.key.json and the Issue #69 approved packages.",
  "-- Only releases reproduced from their control vectors are added; a package whose",
  "-- presentation differs stays out of the allowlist:",
  ...unsupported.map(item => "--   " + item.method_id + " -> " + item.reason)
].join("\n");

fs.writeFileSync(target, header + "\n\n" + newAllow + "\n$$;\n\n" + newGuard + "\n$$;\n", "utf8");

// The pinned-identity CHECK constraint enumerates every accepted release, so the new
// identities are appended to it in a separate append-only migration.
const constraintHeader = "ALTER TABLE instrument_releases ADD CONSTRAINT instrument_release_pinned_identity CHECK(";
const constraintStart = sql.indexOf(constraintHeader);
if (constraintStart < 0) throw new Error("CONSTRAINT_NOT_FOUND");
const constraintEnd = sql.indexOf(");", constraintStart);
if (constraintEnd < 0) throw new Error("CONSTRAINT_END_NOT_FOUND");
const constraintBody = sql.slice(constraintStart + constraintHeader.length, constraintEnd);
const identityClause = release => ` OR (method_id='${release.id}' AND method_version_id='${release.methodVersionId}'
   AND handler_version='${release.handlerVersion}' AND key_digest='${release.keyDigest}' AND verification_state='legacy_checked'
   AND form_id='${release.form.id}' AND form_version='${release.form.version}' AND form_digest='${release.formDigest}')`;
const identity = [
  "SET LOCAL search_path=pedpsy,pg_catalog;",
  "-- 049: accept the approved-library release identities in the pinned-identity guard.",
  "-- Generated together with 048 by scripts/generate-approved-v1-migration.js.",
  "ALTER TABLE instrument_releases DROP CONSTRAINT IF EXISTS instrument_release_pinned_identity;",
  constraintHeader + constraintBody + releases.map(identityClause).join("") + ")\n;"
].join("\n");

fs.writeFileSync(path.join(root, "storage", "postgres", "049_approved_v1_identity.sql"), identity + "\n", "utf8");
console.log("migration written: " + path.relative(root, target) + " releases=" + releases.length + " unsupported=" + unsupported.length);
console.log("migration written: storage/postgres/049_approved_v1_identity.sql");
