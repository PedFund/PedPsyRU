#!/usr/bin/env node
// Emits an append-only delta migration for releases that are not yet in the latest
// allowlist migration. The base statements are copied verbatim so previously pinned
// releases cannot drift; only new clauses are appended.
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const {approvedV1Releases} = require("../storage/approved-v1-release.js");

const root = path.resolve(__dirname, "..");
const directory = path.join(root, "storage", "postgres");
// The allowlist/guard live in one migration and the identity constraint in the next.
const allowList = process.argv[2] || "048_approved_v1_releases.sql";
const constraintList = process.argv[3] || "049_approved_v1_identity.sql";
const output = process.argv[4] || "050_approved_v1_extra.sql";
const base = fs.readFileSync(path.join(directory, allowList), "utf8");
const constraintBase = fs.readFileSync(path.join(directory, constraintList), "utf8");

const {releases} = approvedV1Releases();
const pending = releases.filter(release => !base.includes("'" + release.methodVersionId + "'"));
if (!pending.length) {
  console.log("nothing to append: every release is already pinned");
  process.exit(0);
}

const functionStart = base.indexOf("CREATE OR REPLACE FUNCTION constructor_release_allowed");
const functionEnd = base.indexOf("$$;", functionStart);
if (functionStart < 0 || functionEnd < 0) throw new Error("ALLOWLIST_NOT_FOUND");
const allowBody = base.slice(functionStart, functionEnd).trimEnd();

const guardStart = base.indexOf("CREATE OR REPLACE FUNCTION guard_assignment");
const guardEnd = base.indexOf("$$;", guardStart);
if (guardStart < 0 || guardEnd < 0) throw new Error("GUARD_NOT_FOUND");
const guardBody = base.slice(guardStart, guardEnd);

const constraintHeader = "ALTER TABLE instrument_releases ADD CONSTRAINT instrument_release_pinned_identity CHECK(";
const constraintStart = constraintBase.lastIndexOf(constraintHeader);
if (constraintStart < 0) throw new Error("CONSTRAINT_NOT_FOUND");
const constraintText = constraintBase.slice(constraintStart).replace(/\)\s*;\s*$/, "");
if (constraintText === constraintBase.slice(constraintStart)) throw new Error("CONSTRAINT_TERMINATOR_NOT_FOUND");

const clause = release => ` OR EXISTS(SELECT 1 FROM pedpsy.instrument_releases r WHERE r.id=release AND r.method_id='${release.id}'
   AND r.form_id='${release.form.id}' AND r.form_version='${release.form.version}' AND r.method_version_id='${release.methodVersionId}'
   AND r.handler_version='${release.handlerVersion}' AND r.contract_version='1.0' AND r.verification_state='legacy_checked'
   AND r.publication_state='draft' AND r.form_digest='${release.formDigest}' AND r.key_digest='${release.keyDigest}'
   AND (SELECT count(*) FROM pedpsy.release_items i WHERE i.release_id=r.id)=${release.itemCount}
   AND NOT EXISTS(SELECT 1 FROM pedpsy.release_items i WHERE i.release_id=r.id
     AND (i.ordinal>${release.itemCount} OR i.options IS DISTINCT FROM r.form_snapshot->'items'->(i.ordinal-1)->'options')))`;

const identityClause = release => ` OR (method_id='${release.id}' AND method_version_id='${release.methodVersionId}'
   AND handler_version='${release.handlerVersion}' AND key_digest='${release.keyDigest}' AND verification_state='legacy_checked'
   AND form_id='${release.form.id}' AND form_version='${release.form.version}' AND form_digest='${release.formDigest}')`;

const cases = pending.map(release =>
  `WHEN (SELECT method_id FROM pedpsy.instrument_releases WHERE id=NEW.release_id)='${release.id}' THEN ${release.itemCount} `).join("");
const newGuard = guardBody.replace("ELSE 30 END)", cases + "ELSE 30 END)");
if (newGuard === guardBody) throw new Error("GUARD_CASE_NOT_FOUND");

const sql = [
  "SET LOCAL search_path=pedpsy,pg_catalog;",
  "-- " + output.replace(/^\d+_|\.sql$/g, "") + ": extend the allowlist for further approved releases.",
  "-- Generated by scripts/generate-approved-v1-delta.js from " + allowList + " + " + constraintList + ".",
  "CREATE OR REPLACE FUNCTION constructor_release_allowed(release uuid) RETURNS boolean LANGUAGE sql SECURITY DEFINER SET search_path=pg_catalog,pedpsy,pg_temp AS $$" +
    allowBody.slice(allowBody.indexOf("$$") + 2) + pending.map(clause).join(""),
  "$$;",
  newGuard + "$$;",
  "ALTER TABLE instrument_releases DROP CONSTRAINT IF EXISTS instrument_release_pinned_identity;",
  constraintText + pending.map(identityClause).join("") + ")\n;"
].join("\n");

fs.writeFileSync(path.join(directory, output), sql + "\n", "utf8");
console.log("delta written: " + output + " releases=" + pending.map(release => release.id).join(","));
